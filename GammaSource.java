package cipher;

/**
 * Спільний контракт для будь-якого джерела гами шифру Вернама. Реалізації:
 * {@link LcgGammaKey} (детермінований лінійний конгруентний генератор,
 * компактний ключ -- seed) і {@link SecureGammaKey} (криптографічно-безпечний
 * генератор {@link java.security.SecureRandom}, ключ -- повний масив
 * випадкових байтів). VernamCipher працює з будь-яким джерелом однаково,
 * не знаючи, як саме воно влаштоване всередині.
 */
public interface GammaSource {

    /**
     * Повертає гаму потрібної довжини для накладення на дані такої самої
     * довжини.
     *
     * @param length довжина гами в байтах (має збігатися з довжиною тексту)
     * @throws CipherException якщо довжина некоректна або це джерело не
     *                         може видати гаму такої довжини (наприклад,
     *                         SecureGammaKey згенеровано для іншої довжини)
     */
    byte[] gammaFor(int length) throws CipherException;

    /** Короткий, зрозумілий людині опис ключа для рядка стану меню. */
    String describe();
}
